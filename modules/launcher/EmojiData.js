// Each line split into its parts. Every entry is already a launcher row.
var LIST = RAW.map(function (line) {
    var p = line.split("|")
    return { kind: "emoji", char: p[0], name: p[1], words: (p[2] || "").toLowerCase() }
})

// How well an emoji matches what is typed: lower is better, -1 is no match
function score(e, q) {
    var name = e.name.toLowerCase()
    if (name.indexOf(q) === 0) return 0
    if (name.indexOf(" " + q) !== -1) return 1
    if (name.indexOf(q) !== -1) return 2
    if (e.words.indexOf(q) !== -1) return 3
    return -1
}

// The emoji that match, best match first. Nothing typed lists them all in the order above.
function search(text) {
    var q = text.trim().toLowerCase()
    if (q === "") return LIST
    return LIST
        .map(function (e, i) { return { e: e, s: score(e, q), i: i } })
        .filter(function (m) { return m.s >= 0 })
        .sort(function (a, b) { return a.s - b.s || a.i - b.i })
        .map(function (m) { return m.e })
}